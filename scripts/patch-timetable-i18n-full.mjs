function formatBlock(t) {
  const lines = Object.entries(t).map(([k, v]) => `    ${k}: "${v.replace(/"/g, '\\"')}",`);
  return `  timetable: {\n${lines.join("\n")}\n  },`;
}

const dir = "src/i18n/resources";
for (const [loc, t] of Object.entries(locales)) {
  const file = path.join(dir, `${loc}.ts`);
  let content = fs.readFileSync(file, "utf8");
  const block = formatBlock(t);
  if (content.includes("  timetable: {")) {
    content = content.replace(/ {2}timetable: \{[\s\S]*?\n {2}\},/, block);
  } else {
    content = content.replace(/(\n {2}notifications: \{)/, `\n${block}$1`);
  }
  fs.writeFileSync(file, content);
  console.log("patched full timetable", loc);
}
